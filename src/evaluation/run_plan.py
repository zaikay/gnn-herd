"""Estimate resources from shapes and the frozen budget; never benchmark a fit."""
import json
from pathlib import Path

import pandas as pd

from evaluation.frozen import frozen_protocol
from evaluation.protocol import fit_budget, training_calendar
from evaluation.baselines import validation_rows
from features.panel import load_panel
from features.builder import FeatureBuilder


def main():
    cfg, signature = frozen_protocol()
    panel = load_panel()
    builder = FeatureBuilder(panel)
    rows = validation_rows(cfg)
    records = []
    for fit_origin in rows.fit_origin.drop_duplicates():
        _, mask = training_calendar(fit_origin, cfg['splits']['training_first_target'])
        n = int(mask.sum()) * int(panel.observed.sum())
        for spatial,label in ((False,'gradient_boosting_own'),(True,'gradient_boosting_neighbours')):
            columns = len(builder.names(spatial))
            records.append({'condition':label,'fit_origin':fit_origin,'eligible_training_rows':n,
                            'feature_columns':columns,'float32_matrix_gib':n*columns*4/2**30})
    output = Path('reports/experiments')
    output.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(records).to_csv(output/'t02_cpu_dataset_sizes.csv', index=False)
    budget = fit_budget(cfg)
    total = 2*budget['unique_fits']
    scenarios = [{'assumed_minutes_per_fit':m,'hours_for_92_fits':total*m/60} for m in (2,10,30)]
    plan = {'protocol_sha256':signature,'device':'CPU only','fit_count_per_boosting_condition':budget['unique_fits'],
        'boosting_conditions':2,'total_cpu_fits':total,'validation_origins':len(rows),
        'training_rows_min':min(r['eligible_training_rows'] for r in records),
        'training_rows_max':max(r['eligible_training_rows'] for r in records),
        'float32_matrix_gib_max':max(r['float32_matrix_gib'] for r in records),
        'runtime_status':'unknown until researcher fits; scenarios are arithmetic, not benchmarks',
        'runtime_scenarios':scenarios,'suggested_threads':8,'sequential_fits':True,
        'system_ram_planning_gb':[8,16], 'additional_time':'dataset construction, prediction, grouped permutation and report rendering',
        'resume':'fingerprinted checkpoints reuse completed identical fits; complete runs are not repeated',
        'model_fits_run_by_agent':0,'final_test':'sealed'}
    (output/'t02_cpu_run_plan.json').write_text(json.dumps(plan,indent=2),encoding='utf-8')
    text = ['# Task 2 Part B CPU run plan', '',
        'No model training has run. All estimator fits are researcher-run and CPU-only, including fits that might take less than five minutes. The frozen protocol, grids and seeds are unchanged.', '',
        f"Budget: {total} CPU boosting fits, {budget['unique_fits']} per condition. Composition per condition: 12 tuning + 36 selected validation − 2 reused anchor fits. Seasonal naive has no fitting. No test forecasts or test errors.", '',
        f"Largest planned training table: {plan['training_rows_max']:,} eligible rows. Own-lag features: {len(builder.names(False))}; spatial features: {len(builder.names(True))}. Largest raw float32 matrix: {plan['float32_matrix_gib_max']:.3f} GiB, before estimator copies, histograms and scratch space. Plan for 8–16 GB RAM, one fit at a time, eight CPU threads; this is an estimate, not measured peak RAM. Shapes for every refit: t02_cpu_dataset_sizes.csv.", '',
        'Runtime is unknown without training. Sensitivity only (not a predicted range):', '',
        '| Assumed minutes per fit | Hours for all CPU fits |','| ---: | ---: |']
    text += [f"| {r['assumed_minutes_per_fit']} | {r['hours_for_92_fits']:.2f} |" for r in scenarios]
    text += ['', 'Preprocessing, predictions and grouped permutation sensitivity are additional. The runner logs wall time for each fit, saves metadata and resumes identical checkpoints after interruption. It does not silently skip failed configurations or add trials. If a fit is too expensive, stop and review the measured log; no ad hoc budget or objective change is authorised.', '',
        'Researcher command sequence is in internal/STATUS.md: install pinned dependencies; run tests (including the real DM package toy check); run models.baselines on CPU; render visuals.baselines_validation. The panel preparation and leakage checks can run within the agent limit and are logged separately.', '',
        'Preparation visuals (not model results): [panel observation coverage](../../data/explore/t02/model_panel_coverage.png) with [CSV](../../data/explore/t02/model_panel_coverage.csv), and [implemented Part B pipeline](../../visuals/00_overview/pipeline_part_b.svg) with its text/CSV definitions. Generated by explore.part_b_preparation.', '',
        'Model checkpoints, predictions and metrics are private data/processed outputs. Visuals and their source remain local-only under the researcher policy. The report remains pending until completed-run metrics exist.', '']
    (output/'t02_run_plan.md').write_text('\n'.join(text),encoding='utf-8')
    pending = output/'baselines_validation.md'
    if not pending.exists():
        pending.write_text('# Validation baselines — awaiting researcher CPU run\n\nImplementation and run plan are being prepared. No baseline results or Gate B answer are available.\n\nSee [CPU run plan](t02_run_plan.md) and internal/STATUS.md for researcher commands. Final test remains sealed.\n',encoding='utf-8')
    print(json.dumps(plan,indent=2))


if __name__ == '__main__':
    main()
